#!/usr/bin/env python3
"""
Phase 7 - OpenMP results. Reads one machine's run directory, written by
tools/run_phase7.sh (or by hand with conduit_bench scale / membw):

  results/phase7/<host>/scale.csv     timings and counters per configuration
  results/phase7/<host>/machine.txt   machine description
  results/phase7/<host>/membw.txt     STREAM triad bandwidth (optional)

and reports:

  1. the two sequential baselines: seq-std (std::sort) and seq-radix
  2. thread scaling per stage at the largest super-block size
  3. end-to-end speedup against both baselines, two OpenMP figures:
       omp-kahn    all four stages parallel, Kahn levelling (the specified pipeline)
       omp-hybrid  stages 1-4 parallel, sequential sweep for levelling
  4. levelling algorithms: sweep vs Kahn vs Bellman-Ford, with relaxation,
     atomic and round counts
  5. loop schedules: dynamic vs static vs guided (conflict-detection time, imbalance)
  6. crossover: the smallest super-block where OpenMP beats seq-radix

Each (target, policy) cell is the mean over the two days' median super-blocks;
each timing in scale.csv is already a median over the measured runs.

Writes summary.md and three figures (PNG) to the run directory.

Usage: python3 report_openmp.py [results/phase7/<host>]
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
POLICIES = ("P1", "P2", "P3")
NAMES = {"P1": "P1 contract", "P2": "P2 slot", "P3": "P3 commutative"}
STAGES = ("extract", "sort", "detect", "csr", "level")

# reference palette, light mode, as in report_parallelism.py
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
HAIRLINE = "#e4e3df"
COLOR = {"P1": "#2a78d6", "P2": "#eb6834", "P3": "#1baf7a"}


def variant(r):
    """Configuration name used throughout the report."""
    if r["impl"] != "omp":
        return r["impl"]
    return {"kahn": "omp-kahn", "sweep": "omp-hybrid", "bf": "omp-bf"}[r["level_algo"]]


def load(run):
    rows = list(csv.DictReader(open(run / "scale.csv")))
    for r in rows:
        for k in ("target", "n", "threads", "records", "edges", "levels", "relaxations",
                  "atomics", "rounds"):
            r[k] = int(r[k])
        for k in ["imbalance"] + [f"t_{s}_ms" for s in STAGES] + ["t_total_ms"]:
            r[k] = float(r[k])
        r["t_s1_4_ms"] = r["t_total_ms"] - r["t_level_ms"]
        r["variant"] = variant(r)
        # the 1k/2k/5k prefixes of the smallest target are their own size class
        r["size"] = r["n"] if r["n"] < r["target"] * 0.9 else r["target"]
    return rows


class Table:
    """Mean over days of each column, keyed by (size, policy, variant, threads, schedule)."""

    def __init__(self, rows):
        self.cells = defaultdict(list)
        for r in rows:
            self.cells[r["size"], r["policy"], r["variant"], r["threads"], r["schedule"]].append(r)

    def get(self, size, policy, var, threads=1, schedule="-", col="t_total_ms"):
        rs = self.cells.get((size, policy, var, threads, schedule))
        return float(np.mean([r[col] for r in rs])) if rs else float("nan")

    def best(self, size, policy, var, threads_list, schedules, col="t_total_ms"):
        """Fastest (threads, schedule, time) for a variant."""
        out = (None, None, float("inf"))
        for t in threads_list:
            for s in schedules:
                v = self.get(size, policy, var, t, s, col)
                if v < out[2]:
                    out = (t, s, v)
        return out


class Doc:
    def __init__(self):
        self.lines = []

    def __call__(self, s=""):
        self.lines.append(s)
        print(s)


def ms(v):
    return "–" if np.isnan(v) else (f"{v:.0f}" if v >= 100 else f"{v:.2f}")


def main():
    run = Path(sys.argv[1]) if len(sys.argv) > 1 else max(
        (ROOT / "results" / "phase7").iterdir(), key=lambda p: p.stat().st_mtime)
    rows = load(run)
    tab = Table(rows)
    sizes = sorted({r["size"] for r in rows})
    big = sizes[-1]
    threads = sorted({r["threads"] for r in rows if r["impl"] == "omp"})
    schedules = sorted({r["schedule"] for r in rows if r["impl"] == "omp"})
    sched = "dynamic" if "dynamic" in schedules else schedules[0]
    has_bf = any(r["variant"] == "omp-bf" for r in rows)
    out = Doc()

    out(f"# Phase 7 — OpenMP pipeline: {run.name}")
    out()
    out(f"Generated by report_openmp.py from {run.name}/scale.csv. "
        "Each cell is the mean over the two days' median super-blocks; each timing is a "
        "median over the measured runs. Times in ms.")
    out()
    out("## 0. Machine")
    out()
    out("```")
    out((run / "machine.txt").read_text().rstrip() if (run / "machine.txt").exists()
        else "machine.txt missing")
    out("```")
    if (run / "membw.txt").exists():
        out()
        out("Memory bandwidth (STREAM triad, best of runs):")
        out()
        out("```")
        out((run / "membw.txt").read_text().rstrip())
        out("```")
    out()

    # 1. baselines ------------------------------------------------------------------
    out(f"## 1. Sequential baselines at {big:,} transactions")
    out()
    out("| policy | baseline | " + " | ".join(STAGES) + " | total |")
    out("|---|---|" + "---:|" * (len(STAGES) + 1))
    for p in POLICIES:
        for v in ("seq-std", "seq-radix"):
            out(f"| {p} | {v} | " + " | ".join(ms(tab.get(big, p, v, col=f"t_{s}_ms"))
                                               for s in STAGES)
                + f" | {ms(tab.get(big, p, v))} |")
    out()
    for p in POLICIES:
        a, b = tab.get(big, p, "seq-std", col="t_sort_ms"), tab.get(big, p, "seq-radix",
                                                                    col="t_sort_ms")
        out(f"- {p}: radix sort is {a / b:.1f}x faster than std::sort "
            f"({ms(a)} → {ms(b)} ms); end to end {tab.get(big, p, 'seq-std') / tab.get(big, p, 'seq-radix'):.2f}x.")
    out()
    out("seq-radix is the fair baseline: OpenMP speedup quoted against seq-std alone "
        "would include the sort-algorithm gain, which owes nothing to parallelism.")
    out()

    # 2. per-stage scaling ----------------------------------------------------------
    out(f"## 2. Thread scaling per stage at {big:,} transactions (schedule {sched})")
    out()
    out("Stage times for omp-kahn; stages 1–4 of omp-hybrid are the same code. "
        "`speedup` = seq-radix stage time / omp stage time.")
    out()
    for p in POLICIES:
        out(f"**{NAMES[p]}**")
        out()
        out("| threads | " + " | ".join(STAGES) + " | stages 1–4 | speedup 1–4 vs seq-radix |")
        out("|---:|" + "---:|" * (len(STAGES) + 2))
        base14 = tab.get(big, p, "seq-radix", col="t_s1_4_ms")
        out("| seq-radix | " + " | ".join(ms(tab.get(big, p, "seq-radix", col=f"t_{s}_ms"))
                                         for s in STAGES) + f" | {ms(base14)} | 1.00 |")
        for t in threads:
            v14 = tab.get(big, p, "omp-kahn", t, sched, "t_s1_4_ms")
            out(f"| {t} | " + " | ".join(ms(tab.get(big, p, "omp-kahn", t, sched, f"t_{s}_ms"))
                                         for s in STAGES)
                + f" | {ms(v14)} | {base14 / v14:.2f} |")
        out()

    # 3. end-to-end -----------------------------------------------------------------
    out(f"## 3. End-to-end speedup at {big:,} transactions (schedule {sched})")
    out()
    out("Speedup = baseline total / OpenMP total; above 1 means OpenMP is faster.")
    out()
    out("| policy | threads | omp-kahn ms | vs seq-std | vs seq-radix | "
        "omp-hybrid ms | vs seq-std | vs seq-radix |")
    out("|---|---:|---:|---:|---:|---:|---:|---:|")
    for p in POLICIES:
        s_std, s_rad = tab.get(big, p, "seq-std"), tab.get(big, p, "seq-radix")
        for t in threads:
            k = tab.get(big, p, "omp-kahn", t, sched)
            h = tab.get(big, p, "omp-hybrid", t, sched)
            out(f"| {p} | {t} | {ms(k)} | {s_std / k:.2f} | {s_rad / k:.2f} | "
                f"{ms(h)} | {s_std / h:.2f} | {s_rad / h:.2f} |")
    out()

    # 4. levelling ------------------------------------------------------------------
    out(f"## 4. Levelling algorithms at {big:,} transactions")
    out()
    out("Counts are deterministic properties of the graph: sweep relaxes each edge once "
        "with no atomics in one pass; Kahn relaxes each edge once with 2m + n atomics in "
        "L rounds; Bellman-Ford (Jacobi) re-relaxes every edge each round for L rounds.")
    out()
    out("| policy | edges m | levels L | algorithm | threads | level ms | relaxations | "
        "atomics | rounds | µs per round |")
    out("|---|---:|---:|---|---:|---:|---:|---:|---:|---:|")
    for p in POLICIES:
        rs = tab.cells.get((big, p, "seq-radix", 1, "-"))
        if not rs:
            continue
        m, L = rs[0]["edges"], rs[0]["levels"]
        def line(name, var, t, s):
            lv = tab.get(big, p, var, t, s, "t_level_ms")
            rel = tab.get(big, p, var, t, s, "relaxations")
            at = tab.get(big, p, var, t, s, "atomics")
            rd = tab.get(big, p, var, t, s, "rounds")
            per = f"{lv * 1e3 / rd:.1f}" if rd > 1 else "–"
            out(f"| {p} | {m:,} | {L:,} | {name} | {t} | {ms(lv)} | {rel:,.0f} | {at:,.0f} | "
                f"{rd:,.0f} | {per} |")
        line("sweep", "seq-radix", 1, "-")
        for t in threads:
            line("Kahn", "omp-kahn", t, sched)
        if has_bf:
            bf_sched = sorted({r["schedule"] for r in rows if r["variant"] == "omp-bf"})[0]
            for t in threads:
                line("Bellman-Ford", "omp-bf", t, bf_sched)
    out()

    # 5. schedules ------------------------------------------------------------------
    out(f"## 5. Loop schedules at {big:,} transactions")
    out()
    out("The schedule applies to the per-group loops in conflict detection (count and "
        "emit passes). Imbalance = slowest thread's busy time / mean busy time in the "
        "count pass (1.00 is perfect). Kahn's frontier loop is always dynamic,64.")
    out()
    out("| policy | threads | " + " | ".join(f"{s} detect ms" for s in schedules) + " | "
        + " | ".join(f"{s} imbalance" for s in schedules) + " |")
    out("|---|---:|" + "---:|" * (2 * len(schedules)))
    for p in POLICIES:
        for t in threads:
            if t == 1:
                continue
            out(f"| {p} | {t} | "
                + " | ".join(ms(tab.get(big, p, "omp-hybrid", t, s, "t_detect_ms"))
                             for s in schedules) + " | "
                + " | ".join(f"{tab.get(big, p, 'omp-hybrid', t, s, 'imbalance'):.2f}"
                             for s in schedules) + " |")
    out()

    # 6. crossover ------------------------------------------------------------------
    out("## 6. Crossover: where OpenMP starts to win")
    out()
    out("Best OpenMP configuration (any thread count, any schedule) against seq-radix, "
        "per super-block size.")
    out()
    out("| policy | size | seq-radix ms | best omp-hybrid ms (threads, schedule) | "
        "speedup | best omp-kahn ms | speedup |")
    out("|---|---:|---:|---:|---:|---:|---:|")
    for p in POLICIES:
        for n in sizes:
            b = tab.get(n, p, "seq-radix")
            th, sh, h = tab.best(n, p, "omp-hybrid", threads, schedules)
            _, _, k = tab.best(n, p, "omp-kahn", threads, schedules)
            out(f"| {p} | {n:,} | {ms(b)} | {ms(h)} ({th}, {sh}) | {b / h:.2f} | "
                f"{ms(k)} | {b / k:.2f} |")
    out()
    for p in POLICIES:
        for var in ("omp-hybrid", "omp-kahn"):
            wins = [n for n in sizes
                    if tab.best(n, p, var, threads, schedules)[2] < tab.get(n, p, "seq-radix")]
            # crossover = smallest size from which OpenMP wins at every larger size
            c = next((n for n in sizes if all(x in wins for x in sizes if x >= n)), None)
            out(f"- {p} {var}: " + (f"beats seq-radix from {c:,} transactions upward"
                                    if c else "never beats seq-radix at the sizes measured"))
    out()

    (run / "summary.md").write_text("\n".join(out.lines) + "\n")
    figures(run, tab, sizes, threads, schedules, sched)
    print(f"\nwrote {run / 'summary.md'} and 3 figures")


# ---- figures -----------------------------------------------------------------------

def style(plt):
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "font.family": "sans-serif", "font.size": 10,
        "text.color": INK, "axes.labelcolor": INK_2, "axes.edgecolor": HAIRLINE,
        "xtick.color": INK_2, "ytick.color": INK_2, "axes.linewidth": 0.8,
        "axes.grid": True, "grid.color": HAIRLINE, "grid.linewidth": 0.6,
        "grid.linestyle": "-", "axes.spines.top": False, "axes.spines.right": False,
        "legend.frameon": False,
    })


def figures(run, tab, sizes, threads, schedules, sched):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from matplotlib.ticker import FuncFormatter, LogLocator, NullFormatter
    style(plt)
    plain = FuncFormatter(lambda v, _: f"{v:g}")
    big = sizes[-1]

    def logy(ax):
        ax.set_yscale("log")
        ax.yaxis.set_major_locator(LogLocator(subs=(1, 2, 5)))
        ax.yaxis.set_major_formatter(plain)
        ax.yaxis.set_minor_formatter(NullFormatter())

    def thread_axis(ax):
        ax.set_xscale("log", base=2)
        ax.set_xticks(threads)
        ax.xaxis.set_major_formatter(plain)
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.set_xlabel("OpenMP threads")

    # 1. end-to-end speedup vs seq-radix: hybrid solid, kahn dashed
    fig, ax = plt.subplots(figsize=(7.5, 4.6))
    for p in POLICIES:
        base = tab.get(big, p, "seq-radix")
        for var, ls in (("omp-hybrid", "-"), ("omp-kahn", "--")):
            y = [base / tab.get(big, p, var, t, sched) for t in threads]
            ax.plot(threads, y, color=COLOR[p], linewidth=2, linestyle=ls, marker="o",
                    markersize=5, markeredgecolor=SURFACE, markeredgewidth=1.5)
    ax.axhline(1, color=INK_2, linewidth=1)
    ax.annotate("seq-radix = 1", (threads[0], 1), xytext=(4, 4), textcoords="offset points",
                color=INK_2, fontsize=8)
    logy(ax)
    thread_axis(ax)
    ax.set_ylabel("speedup over seq-radix (end to end)")
    handles = [Line2D([], [], color=COLOR[p], linewidth=2, label=NAMES[p]) for p in POLICIES]
    handles += [Line2D([], [], color=INK_2, linewidth=2, label="omp-hybrid (sweep levelling)"),
                Line2D([], [], color=INK_2, linewidth=2, linestyle="--",
                       label="omp-kahn (parallel levelling)")]
    fig.legend(handles=handles, loc="lower center", ncol=3, fontsize=8.5)
    fig.suptitle(f"End-to-end speedup at {big // 1000}k transactions: Kahn levelling "
                 "turns a gain into a loss", x=0.01, ha="left", fontsize=11)
    fig.tight_layout(rect=(0, 0.11, 1, 1))
    fig.savefig(run / "fig_p7_speedup.png", dpi=200)
    plt.close(fig)

    # 2. per-stage time vs threads, one panel per stage, P1-P3 lines, seq-radix dotted
    fig, axes = plt.subplots(1, len(STAGES), figsize=(13, 3.8), sharex=True)
    for ax, s in zip(axes, STAGES):
        for p in POLICIES:
            y = [tab.get(big, p, "omp-kahn", t, sched, f"t_{s}_ms") for t in threads]
            ax.plot(threads, y, color=COLOR[p], linewidth=2, marker="o", markersize=4,
                    markeredgecolor=SURFACE, markeredgewidth=1.2, label=NAMES[p])
            ax.axhline(tab.get(big, p, "seq-radix", col=f"t_{s}_ms"), color=COLOR[p],
                       linewidth=1, linestyle=":")
        logy(ax)
        thread_axis(ax)
        ax.set_title("level (Kahn)" if s == "level" else s, loc="left", fontsize=10,
                     color=INK_2)
    axes[0].set_ylabel("stage time (ms)")
    handles, labels = axes[0].get_legend_handles_labels()
    handles.append(Line2D([], [], color=INK_2, linewidth=1, linestyle=":"))
    labels.append("seq-radix (same policy)")
    fig.legend(handles, labels, loc="lower center", ncol=4, fontsize=8.5)
    fig.suptitle(f"Stage times at {big // 1000}k transactions, schedule {sched}",
                 x=0.01, ha="left", fontsize=11)
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(run / "fig_p7_stages.png", dpi=200)
    plt.close(fig)

    # 3. crossover: speedup of the best omp-hybrid over seq-radix vs size
    fig, ax = plt.subplots(figsize=(7.5, 4.4))
    for p in POLICIES:
        y = [tab.get(n, p, "seq-radix") / tab.best(n, p, "omp-hybrid", threads, schedules)[2]
             for n in sizes]
        ax.plot(sizes, y, color=COLOR[p], linewidth=2, marker="o", markersize=5,
                markeredgecolor=SURFACE, markeredgewidth=1.5, label=NAMES[p])
    ax.axhline(1, color=INK_2, linewidth=1)
    ax.set_xscale("log")
    ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v / 1000:g}k"))
    ax.xaxis.set_minor_formatter(NullFormatter())
    ax.set_xticks(sizes)
    ax.tick_params(axis="x", labelsize=8)
    ax.set_xlabel("super-block size (transactions)")
    ax.set_ylabel("best omp-hybrid speedup over seq-radix")
    fig.legend(loc="lower center", ncol=3, fontsize=9)
    fig.suptitle("Crossover: best OpenMP configuration against seq-radix; "
                 "above 1 = OpenMP wins", x=0.01, ha="left", fontsize=11)
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.savefig(run / "fig_p7_crossover.png", dpi=200)
    plt.close(fig)


if __name__ == "__main__":
    main()
